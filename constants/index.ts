    `You are an expert in ATS (Applicant Tracking System) and resume analysis.
      Please analyze and rate this resume and suggest how to improve it.
      The rating can be low if the resume is bad.
      Be thorough and detailed. Don't be afraid to point out any mistakes or areas for improvement.
      If there is a lot to improve, don't hesitate to give low scores. This is to help the user to improve their resume.
      If available, use the job description for the job user is applying to to give more detailed feedback.
      If provided, take the job description into consideration.
      The job title is: ${jobTitle}
      The job description is: ${jobDescription}
      Provide the feedback using the following format:
      ${AIResponseFormat}
      Return the analysis as an JSON object, without any other text and without the backticks.
      Do not include any other text or comments.`;

export const JobMatchResponseFormat = `
interface JobMatchAnalysis {
  matchScore: number; // overall match score from 0 to 100

  summary: string; // short explanation of the overall match

  matchingSkills: string[]; // skills from the resume that match the job

  missingSkills: string[]; // important skills required by the job but missing from the resume

  matchingKeywords: string[]; // important job-description keywords already present in the resume

  missingKeywords: string[]; // important keywords from the job description missing from the resume

  experienceMatch: {
    score: number; // 0 to 100
    explanation: string;
  };

  atsCompatibility: {
    score: number; // 0 to 100
    tips: string[]; // 3 to 5 actionable ATS suggestions
  };

  recommendations: string[]; // 4 to 6 actionable recommendations
}
`;

export const prepareJobMatchInstructions = ({
    jobDescription,
}: {
    jobDescription: string;
}) => `
You are an expert technical recruiter, ATS specialist, and career coach.

Analyze the candidate's resume against the provided job description.

Your goal is to determine how well the candidate's resume matches the job and provide actionable recommendations that can improve their chances of getting shortlisted.

IMPORTANT RULES:

1. Evaluate only information actually present in the resume.
2. Do not invent skills, technologies, experience, projects, education, or achievements.
3. Distinguish between skills that are completely missing and skills that may be related or transferable.
4. Prioritize important requirements from the job description over generic keywords.
5. The match score must reflect the actual alignment between the resume and job description.
6. ATS recommendations should be practical and specific.
7. Keep recommendations concise and actionable.
8. Return ONLY raw JSON.
9. Do NOT use Markdown code fences.
10.Do NOT include explanations before or after the JSON.
11.The JSON must follow this exact structure:

${JobMatchResponseFormat}

JOB DESCRIPTION:

${jobDescription}
`;

